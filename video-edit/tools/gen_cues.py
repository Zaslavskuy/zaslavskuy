"""Resolve cues.json against the cut's words and write the numbers into the composition.

usage: python3 tools/gen_cues.py [--cues cues.json] [--words transcripts/final_words.json]
                                 [--plan .tmp/cut_plan.json] [--project project]

Writes (1) the block between `/* CUES:BEGIN */` and `/* CUES:END */` in every
.html of the project (index + compositions/) as `const CUE = {...}; const CLIP =
{...};` — absolute seconds; sub-compositions subtract their own CLIP start — and
(2) data-start / data-duration on every element carrying data-clip="<name>" in
index.html, plus the root data-duration (= clip "video"). Words match without edge punctuation and case: whisper flips between
"эти" / "эти." / "Эти" from run to run. All times snap to the frame grid.
"""
import argparse
import glob
import json
import os
import re

from audiolib import load_json

ap = argparse.ArgumentParser()
ap.add_argument("--cues", default="cues.json")
ap.add_argument("--words", default="transcripts/final_words.json")
ap.add_argument("--plan", default=".tmp/cut_plan.json")
ap.add_argument("--project", default="project")
a = ap.parse_args()

cfg = load_json(a.cues)
words = load_json(a.words)["words"]
plan = load_json(a.plan)
fps = plan["fps"]


def norm(s):
    return re.sub(r"^\W+|\W+$", "", s).lower().replace("ё", "е")


def snap(t):
    return round(round(t * fps) / fps, 4)


# piece and span edges in cut time
piece_in, pos, spans = [], 0.0, {}
for p in plan["pieces"]:
    d = (p["f_out"] - p["f_in"]) / fps
    piece_in.append((pos, pos + d))
    s = spans.setdefault(p["span"], [pos, pos + d])
    s[1] = pos + d
    pos += d


def resolve(name, c):
    if "at" in c:
        t = c["at"]
    elif "span" in c:
        t = spans[c["span"]][0 if c.get("edge", "in") == "in" else 1]
    elif "piece" in c:
        t = piece_in[c["piece"] - 1][0 if c.get("edge", "in") == "in" else 1]
    else:
        key, n = norm(c["word"]), c.get("n", 1)
        hits = [w for w in words if norm(w["w"]) == key]
        if len(hits) < n:
            raise SystemExit(f"cue {name}: word '{c['word']}' #{n} not found ({len(hits)} hits)")
        t = hits[n - 1]["t"]
    return snap(max(0.0, t + c.get("offset", 0.0)))


cue = {k: resolve(k, v) for k, v in cfg["cues"].items()}
clip = {}
for name, c in cfg["clips"].items():
    t0 = snap(cue[c["from"]] - c.get("pre", 0.0))
    t1 = snap(cue[c["to"]] + c.get("post", 0.0))
    clip[name] = {"start": t0, "duration": snap(t1 - t0)}

block = (f"/* CUES:BEGIN — generated by tools/gen_cues.py from cues.json, do not edit */\n"
         f"        const CUE = {json.dumps(cue, ensure_ascii=False)};\n"
         f"        const CLIP = {json.dumps(clip, ensure_ascii=False)};\n"
         f"        /* CUES:END */")
files = [os.path.join(a.project, "index.html")] + sorted(glob.glob(os.path.join(a.project, "compositions", "*.html")))
for path in files:
    html = open(path, encoding="utf-8").read()
    html, n = re.subn(r"/\* CUES:BEGIN.*?/\* CUES:END \*/", lambda m: block, html, flags=re.S)
    if n != 1:
        raise SystemExit(f"{path}: CUES:BEGIN/END block not found exactly once")
    if path.endswith("index.html"):
        for name, v in clip.items():
            def fix(m, v=v):
                tag = re.sub(r'data-start="[^"]*"', f'data-start="{v["start"]}"', m.group(0))
                return re.sub(r'data-duration="[^"]*"', f'data-duration="{v["duration"]}"', tag)
            html, k = re.subn(r'<[^>]*\bdata-clip="%s"[^>]*>' % re.escape(name), fix, html)
            if k == 0:
                print(f"warning: no element with data-clip=\"{name}\"")
        total = clip["video"]["duration"]
        html = re.sub(r'(<[^>]*data-composition-id="main"[^>]*?data-duration=")[^"]*(")',
                      lambda m: f"{m.group(1)}{total}{m.group(2)}", html, count=1)
    open(path, "w", encoding="utf-8").write(html)

for k, v in cue.items():
    print(f"  {k:10s} {v:7.2f}")
print(f"{len(cue)} cues, {len(clip)} clips -> {len(files)} files (duration {clip['video']['duration']}s)")
